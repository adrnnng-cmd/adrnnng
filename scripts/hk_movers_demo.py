def _dedupe(rows):
    seen, out = set(), []
    for row in rows:
        if row[0] not in seen:
            seen.add(row[0])
            out.append(row)
    return out


def build_demo() -> dict:
    rng = random.Random(SEED)
    mapper = sync.SectorMapper(sync.load_sector_map())
    rows = _dedupe(UNIVERSE)
    shocks = {sid: rng.gauss(0.2, 1.5) for sid in mapper.order}

    raw_rows = []
    for code, name, industry, price, mcap_bn, in_hsi in rows:
        sector = mapper.sector_for(industry)
        pct = shocks[sector] * 0.9 + rng.gauss(0, 2.4 if not in_hsi else 1.5)
        pct = max(-13.0, min(15.0, pct))
        last = round(price * (1 + pct / 100.0), 3 if price < 1 else 2)
        prev = price
        ratio = rng.uniform(0.0009, 0.0125) if in_hsi or mcap_bn >= 20 else rng.uniform(0.0004, 0.006)
        raw_rows.append({
            "code": f"HK.{code}",
            "name": name,
            "last_price": last,
            "prev_close_price": prev,
            "high_price": max(last, prev) * (1 + rng.uniform(0.0, 0.02)),
            "low_price": min(last, prev) * (1 - rng.uniform(0.0, 0.02)),
            "turnover": mcap_bn * 1e9 * ratio,
            "total_market_val": mcap_bn * 1e9,
            "industry": industry,
            "_hsi": in_hsi,
        })

    built = [(sync.build_stock(r, mapper), r["_hsi"]) for r in raw_rows]
    stocks = [s for s, _ in built if s]
    hsi_rows = [s for s, in_hsi in built if s and in_hsi]

    news = {}
    for row in stocks:
        pool = UP_HEADLINES if row["change_pct"] >= 0 else DOWN_HEADLINES
        news[row["code"]] = {
            "title": rng.choice(pool).format(n=row["name"]),
            "source": NEWS_SOURCE,
            "published_at_hkt": f"2026-11-20 {rng.randint(9, 15):02d}:{rng.randint(0, 59):02d}",
            "url": NEWS_URL,
        }

    doc = sync.build_snapshot(
        now=DEMO_NOW,
        hsi_index={"prev_close": HSI_PREV_CLOSE},
        hsi_rows=hsi_rows,
        stocks=stocks,
        industries=sync.industries_from_stocks(stocks),
        news=news,
        mapper=mapper,
        universe_count=2640,
        data_source="demo",
        notice=NOTICE,
        session="closed",
    )
    # Two ranked rows have no headline, so the empty state is visible in the demo.
    for code in (doc["movers"]["hsi"]["gainers"][4]["code"], doc["movers"]["hk"]["losers"][2]["code"]):
        doc["news"].pop(code, None)
